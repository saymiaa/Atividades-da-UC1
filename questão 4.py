##4. Média das notas Crie um script que leia duas notas 
# de um aluno e mostre a média entre elas.##


##aqui digitamosa notas do alunos##

nota1 = float(input("Digite a primeira nota: "))
nota2 = float(input("Digite a segunda nota: "))

#CÁLCULO DA MÉDIA#
media = (nota1 + nota2) / 2

# RESULTADO#
print(f"Média: {media:.2f}")
